module FA_and_or_clk (clk,
	C,
	S,
	A,
	B,
	Cin
);
  input wire clk;
	output reg C;
	output reg S;
	input wire A;
	input wire B;
	input wire Cin;
	always@(posedge clk)
	begin
	S = (A ^ B) ^ Cin;
	C = ((A & B) | (A & Cin)) | (B & Cin);
	end
endmodule


